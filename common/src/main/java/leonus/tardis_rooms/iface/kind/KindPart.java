package leonus.tardis_rooms.iface.kind;

import net.minecraft.core.Direction;

/**
 * Часть вида передачи в одном интерфейсе: его состояние (соседи, представление для труб) и хуки жизненного цикла.
 * Создаётся вместе с интерфейсом ({@link TransferKind.PartFactory}); все хуки — на сервере, кроме создания.
 * Хуки, которые виду не нужны, можно не реализовывать.
 */
public interface KindPart {
    /**
     * Грань «вставлять» ({@code pull = false}) или «забирать» ({@code pull = true}): одна операция с соседом
     * со своей стороны {@code face}. Вызывается, только если вид включён и доступен, а сторона открыта.
     */
    default void moveFace(Direction face, boolean pull) {}

    /** Настройки интерфейса изменились (виды, направление, связь, стороны). */
    default void invalidate() {}

    /** Раз в секунду, после пересчёта связи. */
    default void tick() {}

    /** Чанк с интерфейсом выгружен. Блок остаётся в мире: соседей и связанных не трогать. */
    default void unload() {}

    /** Интерфейс убран из мира (сломан, заменён). */
    default void remove() {}
}
