package leonus.tardis_rooms.iface;

/**
 * Часть вида, которая знает настоящие запас и ёмкость хранилищ у связанных интерфейсов — для подсказок.
 * Возможность блока для труб и кабелей может называть другую ёмкость (у энергии — условную, чтобы кабели подключались).
 */
public interface LinkedTotals {
    /** {запас, ёмкость} хранилищ у связанных интерфейсов; {0, 0} — хранилищ нет. */
    long[] linkedTotals();
}
